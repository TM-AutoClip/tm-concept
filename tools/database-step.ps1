# Adds the database schema step of a new app version (an EF Core migration written by EF Core's own tooling, never by hand) and writes the
# compiled model again. Run it once per app version that changes ConceptDbContext's mapping, after the mapping change:
#   tools/database-step.ps1 -Name Version0118
# (a version with steps from parallel work names each after its subject: Version0125Costs, Version0125Documents.)
# The step goes to src/TMConcept.Storage/Database/Concrete/Migrations. Each step knows only the schema of the step before it; the app runs
# every missing step in order at the next start (docs/database.md). Do not edit a step that was released: add a new one.
#
# dotnet-ef needs a startup project that references Microsoft.EntityFrameworkCore.Design; that package and the design-time factory stay out
# of the repository: both live in a temporary folder that is removed afterwards. Nothing is sent anywhere but to NuGet (the tool, the package).
param(
    [Parameter(Mandatory = $true)]
    [ValidatePattern('^Version\d{4,}[A-Za-z]*$')]
    [string]$Name
)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
[xml]$packages = Get-Content (Join-Path $root 'Directory.Packages.props')
$efVersion = ($packages.Project.ItemGroup.PackageVersion | Where-Object { $_.Include -eq 'Microsoft.EntityFrameworkCore.Sqlite.Core' }).Version
$storage = Join-Path $root 'src/TMConcept.Storage/TMConcept.Storage.csproj'
$output = Join-Path $root 'src/TMConcept.Storage/Database/Concrete/Migrations'
$work = Join-Path ([IO.Path]::GetTempPath()) ('tmconcept-database-step-' + [Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $work | Out-Null
try {
    & dotnet tool install dotnet-ef --version $efVersion --tool-path (Join-Path $work 'tool')
    if ($LASTEXITCODE -ne 0) { throw 'dotnet-ef could not be installed' }
    # The assembly is named like the tests so it sees the storage's internal context (InternalsVisibleTo).
    @"
<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <OutputType>Exe</OutputType>
    <TargetFramework>net10.0</TargetFramework>
    <AssemblyName>TMConcept.Tests</AssemblyName>
    <ManagePackageVersionsCentrally>false</ManagePackageVersionsCentrally>
  </PropertyGroup>
  <ItemGroup>
    <ProjectReference Include="$storage" />
    <PackageReference Include="Microsoft.EntityFrameworkCore.Design" Version="$efVersion" />
  </ItemGroup>
</Project>
"@ | Set-Content -Encoding utf8 (Join-Path $work 'design.csproj')
    @'
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Design;
using TMConcept.Storage.Database;

internal sealed class DesignTimeFactory : IDesignTimeDbContextFactory<ConceptDbContext>
{
    public ConceptDbContext CreateDbContext(string[] args) => new(new DbContextOptionsBuilder<ConceptDbContext>().UseSqlite("Data Source=:memory:").Options);
}

internal static class Program
{
    private static void Main()
    {
    }
}
'@ | Set-Content -Encoding utf8 (Join-Path $work 'Program.cs')
    & dotnet build (Join-Path $work 'design.csproj') -nologo -m:1
    if ($LASTEXITCODE -ne 0) { throw 'The design-time project did not build' }
    $before = @(Get-ChildItem $output -Filter *.cs -ErrorAction SilentlyContinue | ForEach-Object { $_.Name })
    & (Join-Path $work 'tool/dotnet-ef') migrations add $Name --project $storage --startup-project (Join-Path $work 'design.csproj') `
        --context ConceptDbContext --output-dir Database/Concrete/Migrations --namespace TMConcept.Storage.Database --no-color
    if ($LASTEXITCODE -ne 0) { throw 'dotnet ef migrations add failed' }
    # dotnet-ef puts the model snapshot into a folder named after the namespace: it belongs next to the steps.
    $project = Split-Path $storage -Parent
    foreach ($snapshot in Get-ChildItem $project -Recurse -Filter 'ConceptDbContextModelSnapshot.cs' | Where-Object { $_.DirectoryName -ne $output -and $_.FullName -notmatch '[\\/](bin|obj)[\\/]' }) {
        Move-Item -Force $snapshot.FullName (Join-Path $output $snapshot.Name)
        $folder = Join-Path $project 'TMConcept'
        if (Test-Path $folder) { Remove-Item -Recurse -Force $folder }
    }
    # File name = type name (analyzer TMC0002): 20261116120000_Version0117.cs -> Version0117.cs (EF Core reads the step's id from its
    # [Migration] attribute, not from the file name). The step is tool output: marked as generated, like its designer part.
    foreach ($file in Get-ChildItem $output -Filter *.cs) {
        if ($file.Name -match '^\d{14}_(.+)$') { Rename-Item $file.FullName $Matches[1] }
    }
    $main = Join-Path $output "$Name.cs"
    $mainText = [IO.File]::ReadAllText($main)
    if (-not $mainText.StartsWith('// <auto-generated />')) { [IO.File]::WriteAllText($main, "// <auto-generated />`n" + $mainText) }
    # The repository stores LF line endings and no byte order mark (.gitattributes); dotnet-ef writes CRLF with one.
    foreach ($file in Get-ChildItem $output -Filter *.cs) {
        $text = [IO.File]::ReadAllText($file.FullName) -replace "`r`n", "`n"
        [IO.File]::WriteAllText($file.FullName, $text, (New-Object Text.UTF8Encoding $false))
    }
    $added = @(Get-ChildItem $output -Filter *.cs | Where-Object { $before -notcontains $_.Name } | ForEach-Object { $_.Name })
    Write-Output ("Schema step written: " + ($added -join ', '))
}
finally {
    Remove-Item -Recurse -Force $work -ErrorAction SilentlyContinue
}

# The compiled model follows the same mapping.
& (Join-Path $PSScriptRoot 'compiled-model.ps1')
if ($LASTEXITCODE -ne 0) { throw 'The compiled model could not be written' }
