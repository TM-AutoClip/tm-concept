using System.ComponentModel;
using CommunityToolkit.Mvvm.ComponentModel;
using CommunityToolkit.Mvvm.Input;
using Microsoft.Extensions.Logging;
using TMConcept.Core.Models;
using TMConcept.Core.Music;
using TMConcept.Core.Styles;
using TMConcept.Desktop.Localization;

namespace TMConcept.Desktop.ViewModels;

/// <summary>
/// The profile's (the series') reference video and background music on the video page's model choice (0.1.54, the developer: the template
/// rarely changes — colours, the channel's look — while the reference video and the music change from video to video, so they left the
/// template). The same choices the template had: no music, a piece of "Müziklerim" (made or added on the Müzik üret page), the ready library
/// (with the Openverse search), music generated by a local or an online model, or the user's own file; levels, ducking and fade-out; the
/// reference video by file or address. Every change is saved for the profile (<see cref="Changed"/>; the page writes it) and each video
/// takes it when it starts (<see cref="ToMedia"/>). A music model is chosen like every other model (0.1.55): one not installed yet says so
/// and is installed, after one confirmation together with the video's other downloads, when the video starts (<see cref="GeneratedModel"/>);
/// there is no install button of its own. The ready library is data, not a model: it is still installed from here before it can be chosen.
/// </summary>
public sealed partial class VideoMediaViewModel : ObservableObject, IDisposable
{
    private readonly IVideoMediaServices _services;
    private readonly IMyMusic _myMusic;
    private readonly IMusicChoiceText _labels;
    private readonly Localizer _text;
    private readonly ILogger<VideoMediaViewModel> _logger;
    private MusicGeneratorServices? _generators;
    private VideoMusic _music = new();
    private bool _filling;
    private MusicSourceChoice? _lastSource;

    /// <summary>Creates the empty form (<see cref="LoadAsync"/> fills it).</summary>
    public VideoMediaViewModel(IVideoMediaServices services, IMyMusic myMusic, IMusicChoiceText labels, Localizer text, ILogger<VideoMediaViewModel> logger)
    {
        ArgumentNullException.ThrowIfNull(services);
        ArgumentNullException.ThrowIfNull(myMusic);
        ArgumentNullException.ThrowIfNull(labels);
        ArgumentNullException.ThrowIfNull(text);
        _services = services;
        _myMusic = myMusic;
        _labels = labels;
        _text = text;
        _logger = logger;
        MusicSources = [];
        LocalMusicModels = [];
        OnlineMusicModels = [];
        MyTracks = [];
        MusicSource = new MusicSourceChoice((int)Core.Styles.MusicSource.Off, text["style.music.off"], true);
    }

    /// <summary>A change worth saving (not while the form is filled).</summary>
    public event EventHandler? Changed;

    /// <summary>The library music's part of the form; null before the first load.</summary>
    [ObservableProperty]
    public partial MusicPickerViewModel? MusicPicker { get; set; }

    /// <summary>The reference video's part of the form; null before the first load.</summary>
    [ObservableProperty]
    public partial ReferenceVideoViewModel? ReferenceVideo { get; set; }

    /// <summary>The music sources (the library enabled only when installed).</summary>
    [ObservableProperty]
    public partial IReadOnlyList<MusicSourceChoice> MusicSources { get; set; }

    /// <summary>Where the background music comes from.</summary>
    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(MusicOn), nameof(MusicOwnFile), nameof(MusicLibrary), nameof(MusicGenerateLocal), nameof(MusicGenerateOnline),
        nameof(MusicGenerated), nameof(MusicCardWarning), nameof(MusicMine), nameof(MyMusicEmpty))]
    public partial MusicSourceChoice MusicSource { get; set; }

    /// <summary>A short note under the source: why a source cannot be chosen yet (empty = nothing to say).</summary>
    [ObservableProperty]
    public partial string MusicNote { get; set; } = string.Empty;

    /// <summary>The local music models with their install state and card note.</summary>
    [ObservableProperty]
    public partial IReadOnlyList<MusicModelOption> LocalMusicModels { get; set; }

    /// <summary>The chosen local music model.</summary>
    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(MusicCardWarning))]
    public partial MusicModelOption? LocalMusicModel { get; set; }

    /// <summary>The online music models with their prices.</summary>
    [ObservableProperty]
    public partial IReadOnlyList<MusicModelOption> OnlineMusicModels { get; set; }

    /// <summary>The chosen online music model.</summary>
    [ObservableProperty]
    public partial MusicModelOption? OnlineMusicModel { get; set; }

    /// <summary>The pieces of "Müziklerim".</summary>
    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(MyMusicEmpty))]
    public partial IReadOnlyList<MusicTrackOption> MyTracks { get; set; }

    /// <summary>The chosen piece of "Müziklerim".</summary>
    [ObservableProperty]
    public partial MusicTrackOption? MyTrack { get; set; }

    /// <summary>"Müziklerim" is the source.</summary>
    public bool MusicMine => Is(Core.Styles.MusicSource.MyMusic);

    /// <summary>"Müziklerim" is the source and has nothing yet.</summary>
    public bool MyMusicEmpty => MusicMine && MyTracks.Count == 0;

    /// <summary>The ready library is the source.</summary>
    public bool MusicLibrary => Is(Core.Styles.MusicSource.Library);

    /// <summary>A local model is the source.</summary>
    public bool MusicGenerateLocal => Is(Core.Styles.MusicSource.GenerateLocal);

    /// <summary>An online model is the source.</summary>
    public bool MusicGenerateOnline => Is(Core.Styles.MusicSource.GenerateOnline);

    /// <summary>The music is generated.</summary>
    public bool MusicGenerated => MusicGenerateLocal || MusicGenerateOnline;

    /// <summary>The music has settings to show.</summary>
    public bool MusicOn => !Is(Core.Styles.MusicSource.Off);

    /// <summary>The user's own file is the source.</summary>
    public bool MusicOwnFile => Is(Core.Styles.MusicSource.OwnFile);

    /// <summary>The yellow note of the chosen local model on this computer (a card it is not made for; Linux). Never a block.</summary>
    public string MusicCardWarning => MusicGenerateLocal && _generators is { } services ? _labels.CardWarning(GeneratedModel, services.Card) : string.Empty;

    /// <summary>
    /// The music model the profile's choice makes its music with (the chosen local or online model; null for any other source): a video
    /// makes it ready (licence, key, its downloads in the video's one confirmation) before it starts.
    /// </summary>
    public CatalogModel? GeneratedModel => _generators is null ? null
        : MusicGenerateLocal ? Find(LocalMusicModel?.Key)
        : MusicGenerateOnline ? Find(OnlineMusicModel?.Key)
        : null;

    /// <summary>The own music file's full path.</summary>
    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(MusicFileName))]
    public partial string MusicFile { get; set; } = string.Empty;

    /// <summary>The chosen file's name, or "no file chosen".</summary>
    public string MusicFileName => MusicFile.Length > 0 ? Path.GetFileName(MusicFile) : _text["styles.music.no_file"];

    /// <summary>The attribution the track asks for.</summary>
    [ObservableProperty]
    public partial string MusicAttribution { get; set; } = string.Empty;

    /// <summary>The music's level where nobody speaks (dB).</summary>
    [ObservableProperty]
    public partial decimal? MusicLevel { get; set; } = (decimal)MusicMixDefaults.LevelDb;

    /// <summary>How much lower the music is under narration (dB).</summary>
    [ObservableProperty]
    public partial decimal? MusicDuck { get; set; } = (decimal)MusicMixDefaults.DuckDb;

    /// <summary>The fade-out at the end of the video (seconds).</summary>
    [ObservableProperty]
    public partial decimal? MusicFadeOut { get; set; } = (decimal)MusicMixDefaults.FadeOutSeconds;

    /// <summary>Fills the form from <paramref name="media"/> (a profile's choice; nothing is saved by the filling).</summary>
    public async Task LoadAsync(VideoMedia media)
    {
        ArgumentNullException.ThrowIfNull(media);
        _generators ??= await _services.GeneratorsAsync().ConfigureAwait(true);
        var mine = await ReadMineAsync().ConfigureAwait(true);
        _filling = true;
        try
        {
            _music = media.Music ?? new VideoMusic();
            if (MusicPicker is { } oldPicker)
            {
                oldPicker.PropertyChanged -= OnPickerChanged;
                oldPicker.Dispose();
            }

            MusicPicker = new MusicPickerViewModel(_services.Picker, _text, _music.Source == Core.Styles.MusicSource.Library ? _music.Track : null);
            MusicPicker.PropertyChanged += OnPickerChanged;
            if (ReferenceVideo is { } oldReference)
            {
                oldReference.PropertyChanged -= OnReferenceChanged;
                oldReference.Dispose();
            }

            ReferenceVideo = new ReferenceVideoViewModel(_services.Reference, _text, media.Reference);
            ReferenceVideo.PropertyChanged += OnReferenceChanged;
            LocalMusicModels = Options(local: true);
            OnlineMusicModels = Options(local: false);
            MyTracks = mine;
            MyTrack = _music.Source == Core.Styles.MusicSource.MyMusic
                ? mine.FirstOrDefault(o => o.Track?.Id == _music.Track?.Id) ?? mine.FirstOrDefault()
                : mine.FirstOrDefault();
            MusicSources = SourceChoices();
            MusicSource = MusicSources.FirstOrDefault(c => c.Value == (int)_music.Source) ?? MusicSources[0];
            _lastSource = MusicSource;
            MusicFile = _music.File;
            LocalMusicModel = LocalMusicModels.FirstOrDefault(o => o.Key == _music.Generator) ?? LocalMusicModels.FirstOrDefault();
            OnlineMusicModel = OnlineMusicModels.FirstOrDefault(o => o.Key == _music.Generator) ?? OnlineMusicModels.FirstOrDefault();
            MusicAttribution = _music.Attribution;
            MusicLevel = (decimal)Math.Round(_music.LevelDb, 1);
            MusicDuck = (decimal)Math.Round(_music.DuckDb, 1);
            MusicFadeOut = (decimal)Math.Round(_music.FadeOutSeconds, 1);
            MusicNote = string.Empty;
        }
        finally
        {
            _filling = false;
        }

        OnPropertyChanged(nameof(MusicCardWarning));
    }

    /// <summary>
    /// Reads "Müziklerim" again (a piece made or added on the music page) and the models' install state (a model installed by a video or the
    /// music page no longer says "not installed"); the chosen piece and models stay when they are still there.
    /// </summary>
    public async Task RefreshMineAsync()
    {
        var mine = await ReadMineAsync().ConfigureAwait(true);
        var chosen = MyTrack?.Track?.Id;
        var local = LocalMusicModel?.Key;
        var online = OnlineMusicModel?.Key;
        _filling = true;
        try
        {
            MyTracks = mine;
            MyTrack = mine.FirstOrDefault(o => o.Track?.Id == chosen) ?? mine.FirstOrDefault();
            if (_generators is not null)
            {
                LocalMusicModels = Options(local: true);
                OnlineMusicModels = Options(local: false);
                LocalMusicModel = LocalMusicModels.FirstOrDefault(o => o.Key == local) ?? LocalMusicModels.FirstOrDefault();
                OnlineMusicModel = OnlineMusicModels.FirstOrDefault(o => o.Key == online) ?? OnlineMusicModels.FirstOrDefault();
            }
        }
        finally
        {
            _filling = false;
        }

        OnPropertyChanged(nameof(MyMusicEmpty));
    }

    /// <summary>The form as the profile's choice.</summary>
    public VideoMedia ToMedia() => new()
    {
        Music = new VideoMusic
        {
            Source = (Core.Styles.MusicSource)(MusicSource?.Value ?? 0),
            File = MusicFile.Trim(),
            Track = MusicLibrary ? MusicPicker?.Track : MusicMine ? MyTrack?.Track : null,
            Generator = MusicGenerateLocal ? LocalMusicModel?.Key ?? _music.Generator
                : MusicGenerateOnline ? OnlineMusicModel?.Key ?? _music.Generator
                : string.Empty,
            Instrumental = _music.Instrumental,
            Attribution = MusicAttribution.Trim(),
            LevelDb = (double)Math.Clamp(MusicLevel ?? (decimal)MusicMixDefaults.LevelDb, (decimal)MusicMixDefaults.MinLevelDb, (decimal)MusicMixDefaults.MaxLevelDb),
            DuckDb = (double)Math.Clamp(MusicDuck ?? (decimal)MusicMixDefaults.DuckDb, (decimal)MusicMixDefaults.MinDuckDb, 0m),
            FadeOutSeconds = (double)Math.Clamp(MusicFadeOut ?? (decimal)MusicMixDefaults.FadeOutSeconds, 0m, (decimal)MusicMixDefaults.MaxFadeOutSeconds),
        },
        Reference = ReferenceVideo?.Profile,
    };

    /// <summary>Asks for the own music file.</summary>
    [RelayCommand]
    public async Task PickMusicAsync()
    {
        if (await _services.PickMusicFileAsync().ConfigureAwait(true) is { Length: > 0 } file)
        {
            MusicFile = file;
        }
    }

    /// <inheritdoc />
    public void Dispose()
    {
        MusicPicker?.Dispose();
        ReferenceVideo?.Dispose();
    }

    /// <inheritdoc />
    protected override void OnPropertyChanged(PropertyChangedEventArgs e)
    {
        ArgumentNullException.ThrowIfNull(e);
        base.OnPropertyChanged(e);
        if (_filling || e.PropertyName is not (nameof(MusicSource) or nameof(MusicFile) or nameof(MusicAttribution) or nameof(MusicLevel)
            or nameof(MusicDuck) or nameof(MusicFadeOut) or nameof(LocalMusicModel) or nameof(OnlineMusicModel) or nameof(MyTrack)))
        {
            return;
        }

        if (e.PropertyName == nameof(MusicSource))
        {
            // The ready library (data, not a model) can be chosen only once installed (rule 18: never downloaded by itself). A music model is
            // chosen as it is and installed when the video starts, like every other model.
            if (MusicLibrary && MusicPicker is not { Ready: true } && _lastSource is not null && _lastSource.Value != MusicSource.Value)
            {
                MusicNote = _text["styles.music.library.not_ready"];
                _filling = true;
                MusicSource = _lastSource;
                _filling = false;
                return;
            }

            MusicNote = string.Empty;
            _lastSource = MusicSource;
        }

        Changed?.Invoke(this, EventArgs.Empty);
    }

    private bool Is(Core.Styles.MusicSource source) => (MusicSource?.Value ?? 0) == (int)source;

    private CatalogModel? Find(string? key) => key is null ? null : _generators?.Models.FirstOrDefault(m => ModelBase.KeyOf(m) == key);

    private List<MusicModelOption> Options(bool local) => _generators is not { } services
        ? []
        : services.Models.Where(m => (m.Provider == ModelProviders.Local) == local)
            .Select(m => new MusicModelOption(ModelBase.KeyOf(m), _labels.ModelLabel(m, services.Ready(m), services.Card))).ToList();

    private async Task<IReadOnlyList<MusicTrackOption>> ReadMineAsync()
    {
        try
        {
            var entries = await Task.Run(() => _myMusic.ListAsync(CancellationToken.None)).ConfigureAwait(true);
            return entries.Select(e => new MusicTrackOption(e.Track, e.Track.Title, _labels.PieceDetail(e, full: false))).ToList();
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            _logger.LogWarning(ex, "My music could not be read");
            return [];
        }
    }

    private void Rebuild()
    {
        var chosen = MusicSource?.Value ?? 0;
        _filling = true;
        MusicSources = SourceChoices();
        MusicSource = MusicSources.FirstOrDefault(c => c.Value == chosen) ?? MusicSources[0];
        _lastSource = MusicSource;
        _filling = false;
    }

    private void OnPickerChanged(object? sender, PropertyChangedEventArgs e)
    {
        if (e.PropertyName == nameof(MusicPickerViewModel.Ready))
        {
            Rebuild();
            if (MusicPicker is { Ready: true })
            {
                MusicNote = string.Empty;
            }
        }
        else if (e.PropertyName == nameof(MusicPickerViewModel.SelectedTrack) && !_filling && MusicLibrary)
        {
            Changed?.Invoke(this, EventArgs.Empty);
        }
    }

    private void OnReferenceChanged(object? sender, PropertyChangedEventArgs e)
    {
        if (e.PropertyName == nameof(ReferenceVideoViewModel.Profile) && !_filling)
        {
            Changed?.Invoke(this, EventArgs.Empty);
        }
    }

    private List<MusicSourceChoice> SourceChoices() => Core.Styles.MusicSources.Available
        .Where(m => m != Core.Styles.MusicSource.GenerateLocal || LocalMusicModels.Count > 0)
        .Where(m => m != Core.Styles.MusicSource.GenerateOnline || OnlineMusicModels.Count > 0)
        .Select(m => new MusicSourceChoice((int)m, SourceLabel(m), m != Core.Styles.MusicSource.Library || MusicPicker is { Ready: true }))
        .ToList();

    private string SourceLabel(Core.Styles.MusicSource source)
    {
        var key = "style.music." + source.ToString().ToLowerInvariant();
        return _text.Has(key) ? _text[key] : source.ToString();
    }
}
