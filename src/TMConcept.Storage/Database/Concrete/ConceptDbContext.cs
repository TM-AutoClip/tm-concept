using System.Diagnostics.CodeAnalysis;
using System.Linq.Expressions;
using Microsoft.EntityFrameworkCore;
using TMConcept.Core.Concepts;
using TMConcept.Core.Duplicates;
using TMConcept.Core.Keys;
using TMConcept.Core.Models;
using TMConcept.Core.Profiles;
using TMConcept.Core.Pronunciation;
using TMConcept.Core.Runs;
using TMConcept.Core.Speech;
using TMConcept.Core.Videos;

namespace TMConcept.Storage.Database;

/// <summary>
/// The tables of the encrypted database file (names, columns, keys, indexes and cascades as EF Core maps them here). Values keep their
/// stored form through value converters: upper-case TEXT ids, UTC ticks, invariant money text, 0/1 flags; enums are their numbers. Keys are
/// never generated by EF Core (an id is set by the code). Besides the tables: SQLite's own read-only views of the file
/// (<c>sqlite_master</c>, <c>pragma_secure_delete</c>), so even the schema checks go through EF Core.
/// Deleting a profile removes its concepts, queue, image records, embeddings, step choices, topic suggestions, AI-edit wishes and video records; deleting a concept removes
/// its embedding and queue entry and leaves its videos (their link becomes empty).
/// The app runs on the compiled model of this mapping (CompiledModel/, found by EF Core through its assembly attribute): building the model
/// at every start cost about 1 s at the unlock of the trimmed release. After any change here run tools/compiled-model.ps1 (or .sh);
/// CompiledModelTests fails until then. Creating the schema uses the model built from this method (EF
/// Core's design-time model).
/// </summary>
internal sealed class ConceptDbContext(DbContextOptions<ConceptDbContext> options) : DbContext(options)
{
    // What EF Core reads of an entity type by reflection (its own annotation on Set<TEntity>, which it keeps internal).
    private const DynamicallyAccessedMemberTypes EntityMembers = DynamicallyAccessedMemberTypes.PublicConstructors
        | DynamicallyAccessedMemberTypes.NonPublicConstructors | DynamicallyAccessedMemberTypes.PublicFields | DynamicallyAccessedMemberTypes.NonPublicFields
        | DynamicallyAccessedMemberTypes.PublicProperties | DynamicallyAccessedMemberTypes.NonPublicProperties | DynamicallyAccessedMemberTypes.Interfaces;

    /// <summary>Profiles.</summary>
    public DbSet<Profile> Profiles => Set<Profile>();

    /// <summary>Sample images.</summary>
    public DbSet<ProfileImage> ProfileImages => Set<ProfileImage>();

    /// <summary>Concepts.</summary>
    public DbSet<Concept> Concepts => Set<Concept>();

    /// <summary>Concept embeddings.</summary>
    public DbSet<ConceptEmbedding> Embeddings => Set<ConceptEmbedding>();


    /// <summary>Runs.</summary>
    public DbSet<Run> Runs => Set<Run>();

    /// <summary>Production queue.</summary>
    public DbSet<QueueItem> QueueItems => Set<QueueItem>();

    /// <summary>Videos.</summary>
    public DbSet<VideoRecord> Videos => Set<VideoRecord>();

    /// <summary>Video cost lines.</summary>
    public DbSet<VideoCost> VideoCosts => Set<VideoCost>();

    /// <summary>API keys.</summary>
    public DbSet<ApiKey> ApiKeys => Set<ApiKey>();

    /// <summary>Each profile's step choices.</summary>
    public DbSet<StepModelChoice> ProfileStepModels => Set<StepModelChoice>();

    /// <summary>Settings documents.</summary>
    public DbSet<SettingRow> Settings => Set<SettingRow>();

    /// <summary>The user's pronunciation dictionary.</summary>
    public DbSet<PronunciationEntry> Pronunciations => Set<PronunciationEntry>();

    /// <summary>The user's voice samples.</summary>
    public DbSet<VoiceSample> VoiceSamples => Set<VoiceSample>();

    /// <summary>The topics "Suggest topics" brought.</summary>
    public DbSet<TopicSuggestion> TopicSuggestions => Set<TopicSuggestion>();

    /// <summary>The newest AI-edit instructions of each profile.</summary>
    public DbSet<ConceptWish> ConceptWishes => Set<ConceptWish>();

    /// <summary>The file's tables and indexes (<c>sqlite_master</c>).</summary>
    public DbSet<SchemaObjectRow> SchemaObjects => Set<SchemaObjectRow>();

    /// <summary><c>pragma_secure_delete</c>.</summary>
    public DbSet<SecureDeleteRow> SecureDelete => Set<SecureDeleteRow>();

    /// <summary>
    /// Adds <paramref name="row"/>, or replaces every column of the stored row that <paramref name="sameKey"/> finds, and saves. The entity
    /// type carries the members EF Core reads by reflection (the same annotation as <see cref="DbContext.Set{TEntity}()"/>).
    /// </summary>
    public async Task UpsertAsync<[DynamicallyAccessedMembers(EntityMembers)] T>(T row, Expression<Func<T, bool>> sameKey,
        CancellationToken cancellationToken)
        where T : class
    {
        if (await Set<T>().AnyAsync(sameKey, cancellationToken).ConfigureAwait(false))
        {
            Update(row);
        }
        else
        {
            Add(row);
        }

        await SaveChangesAsync(cancellationToken).ConfigureAwait(false);
    }

    /// <inheritdoc />
    protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
    {
        ArgumentNullException.ThrowIfNull(configurationBuilder);
        configurationBuilder.Properties<Guid>().HaveConversion<StoredIdConverter>();
        configurationBuilder.Properties<DateTimeOffset>().HaveConversion<UtcTicksConverter>();
        configurationBuilder.Properties<decimal>().HaveConversion<MoneyConverter>();
        configurationBuilder.Properties<bool>().HaveConversion<FlagConverter>();
    }

    /// <inheritdoc />
    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        ArgumentNullException.ThrowIfNull(modelBuilder);
        modelBuilder.Entity<Profile>(e =>
        {
            e.ToTable(ConceptSchema.Profiles);
            e.HasKey(p => p.Id);
            e.Property(p => p.Id).ValueGeneratedNever();
        });
        modelBuilder.Entity<ProfileImage>(e =>
        {
            e.ToTable("profile_images");
            e.HasKey(i => i.Id);
            e.Property(i => i.Id).ValueGeneratedNever();
            e.HasOne<Profile>().WithMany().HasForeignKey(i => i.ProfileId).OnDelete(DeleteBehavior.Cascade);
        });
        modelBuilder.Entity<Concept>(e =>
        {
            e.ToTable("concepts");
            e.HasKey(c => c.Id);
            e.Property(c => c.Id).ValueGeneratedNever();
            e.HasIndex(c => new { c.ProfileId, c.Number }).IsUnique();
            e.HasIndex(c => new { c.ProfileId, c.Status });
            e.HasOne<Profile>().WithMany().HasForeignKey(c => c.ProfileId).OnDelete(DeleteBehavior.Cascade);
        });
        modelBuilder.Entity<ConceptEmbedding>(e =>
        {
            e.ToTable("concept_embeddings");
            e.HasKey(c => c.ConceptId);
            e.Property(c => c.ConceptId).ValueGeneratedNever();
            e.HasIndex(c => new { c.ProfileId, c.Model });
            e.HasOne<Concept>().WithMany().HasForeignKey(c => c.ConceptId).OnDelete(DeleteBehavior.Cascade);
        });
        modelBuilder.Entity<Run>(e =>
        {
            e.ToTable("runs");
            e.HasKey(r => r.Id);
            e.Property(r => r.Id).ValueGeneratedNever();
            e.HasIndex(r => r.StartedAtUtc);
        });
        modelBuilder.Entity<QueueItem>(e =>
        {
            e.ToTable("queue_items");
            e.HasKey(q => q.Id);
            e.Property(q => q.Id).ValueGeneratedNever();
            e.HasIndex(q => new { q.ProfileId, q.Position });
            e.HasOne<Profile>().WithMany().HasForeignKey(q => q.ProfileId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne<Concept>().WithMany().HasForeignKey(q => q.ConceptId).OnDelete(DeleteBehavior.Cascade);
        });
        modelBuilder.Entity<VideoRecord>(e =>
        {
            e.ToTable("videos");
            e.HasKey(v => v.Id);
            e.Property(v => v.Id).ValueGeneratedNever();
            e.HasIndex(v => new { v.ProfileId, v.CreatedAtUtc });
            e.HasOne<Profile>().WithMany().HasForeignKey(v => v.ProfileId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne<Concept>().WithMany().HasForeignKey(v => v.ConceptId).OnDelete(DeleteBehavior.SetNull);
        });
        modelBuilder.Entity<VideoCost>(e =>
        {
            e.ToTable("video_costs");
            e.HasKey(c => c.Id);
            e.Property(c => c.Id).ValueGeneratedNever();
            e.HasOne<VideoRecord>().WithMany().HasForeignKey(c => c.VideoId).OnDelete(DeleteBehavior.Cascade);
        });
        modelBuilder.Entity<ApiKey>(e =>
        {
            e.ToTable("api_keys");
            e.HasKey(k => k.Id);
            e.Property(k => k.Id).ValueGeneratedNever();
            e.HasIndex(k => k.Provider);
        });
        modelBuilder.Entity<StepModelChoice>(e =>
        {
            e.ToTable(ConceptSchema.ProfileStepModels);
            e.HasKey(s => new { s.ProfileId, s.Step });
            e.HasOne<Profile>().WithMany().HasForeignKey(s => s.ProfileId).OnDelete(DeleteBehavior.Cascade);
        });
        modelBuilder.Entity<SettingRow>(e =>
        {
            e.ToTable(ConceptSchema.Settings);
            e.HasKey(s => s.Key);
        });
        modelBuilder.Entity<PronunciationEntry>(e =>
        {
            e.ToTable("pronunciations");
            e.HasKey(p => p.Id);
            e.Property(p => p.Id).ValueGeneratedNever();
            e.HasIndex(p => p.Language);
        });
        modelBuilder.Entity<VoiceSample>(e =>
        {
            e.ToTable("voice_samples");
            e.HasKey(v => v.Id);
            e.Property(v => v.Id).ValueGeneratedNever();
        });
        modelBuilder.Entity<TopicSuggestion>(e =>
        {
            e.ToTable("topic_suggestions");
            e.HasKey(t => t.Id);
            e.Property(t => t.Id).ValueGeneratedNever();
            e.HasIndex(t => new { t.ProfileId, t.CreatedAtUtc });

            // The selected list of a profile is read by its status (TopicStatus is stored as its number, like every enum here).
            e.HasIndex(t => new { t.ProfileId, t.Status });
            e.HasOne<Profile>().WithMany().HasForeignKey(t => t.ProfileId).OnDelete(DeleteBehavior.Cascade);
        });
        modelBuilder.Entity<ConceptWish>(e =>
        {
            e.ToTable("concept_wishes");
            e.HasKey(w => w.Id);
            e.Property(w => w.Id).ValueGeneratedNever();
            e.HasIndex(w => new { w.ProfileId, w.CreatedAtUtc });
            e.HasOne<Profile>().WithMany().HasForeignKey(w => w.ProfileId).OnDelete(DeleteBehavior.Cascade);
        });
        // SQLite's views of the file. A pragma with an argument is read through its hidden "arg" column (pragma_table_info WHERE arg = …).
        modelBuilder.Entity<SchemaObjectRow>(e =>
        {
            e.HasNoKey().ToView("sqlite_master");
            e.Property(o => o.Type).HasColumnName("type");
            e.Property(o => o.Name).HasColumnName("name");
            e.Property(o => o.Table).HasColumnName("tbl_name");
        });
        modelBuilder.Entity<SecureDeleteRow>(e =>
        {
            e.HasNoKey().ToView("pragma_secure_delete");
            e.Property(v => v.Value).HasColumnName("secure_delete");
        });
    }
}
